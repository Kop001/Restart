"""Приведение русских слов к основе.

Память ищется по словам, а русский склоняет их до неузнаваемости: записано
«место работы», спрашивают «где я работаю» — буквальное сравнение не найдёт
ничего. Полноценная морфология потребовала бы внешней библиотеки и словаря;
здесь достаточно отбросить типовые окончания.

Правило одно: лучше не отрезать, чем отрезать лишнее. Слишком короткая основа
склеивает разные слова, и поиск начинает врать.
"""

from __future__ import annotations

import re

# Окончания от длинных к коротким: «работами» должно потерять «ами», а не «и».
ENDINGS = (
    "иями", "ями", "ами", "ов", "ев", "ий", "ый", "ой", "ей",
    "ого", "его", "ому", "ему", "ыми", "ими", "ыми",
    "ать", "ять", "еть", "ить", "уть", "ють",
    "ешь", "ишь", "ете", "ите", "ется", "ится",
    "ах", "ях", "ам", "ям", "ом", "ем", "ет", "ит", "ут", "ют", "ат", "ят",
    "ая", "яя", "ое", "ее", "ые", "ие", "ла", "ло", "ли",
    "а", "я", "ы", "и", "о", "е", "у", "ю", "ь", "й", "л",
)

# Ниже этого основу не режем: «дом», «код», «сон» — уже основы.
MIN_STEM = 3

# Служебные слова ничего не значат для поиска, но если их не выбросить,
# запрос «где я работаю» потребует найти ещё и «где» с «я» — и не найдёт ничего.
STOP = frozenset("""
а и но или не ни же ли бы что как когда где куда откуда почему зачем
я ты он она оно мы вы они мне меня мной тебе тебя тобой нам нас нами вам вас вами
мой моя мое мои твой твоя твое твои наш наша наше наши ваш ваша ваше ваши
это этот эта эти тот та те такой такая такие весь вся все всё
в во на за под над при про по о об от до из для с со у к
был была было были есть быть будет буду будешь
моей моего моему моим моих твоей твоего твоему твоим
знаешь знаете знаю помнишь помните скажи расскажи напомни покажи

""".split())

_WORD = re.compile(r"\w+", re.UNICODE)


def stem(word: str) -> str:
    """Отбрасывает у слова типовые русские окончания.

    Режем в несколько проходов: «работаю» теряет сначала «ю», потом «а», —
    иначе основа не совпадёт с той, что получилась из «работа». Латиница
    и короткие слова возвращаются как есть.
    """
    word = word.lower().replace("ё", "е")
    if not _is_cyrillic(word):
        return word

    # Два прохода хватает: третьего окончания у русского слова не бывает,
    # а лишний проход уже съедал бы корень.
    for _ in range(2):
        shortened = _strip_once(word)
        if shortened == word:
            break
        word = shortened
    return word


def _strip_once(word: str) -> str:
    if len(word) <= MIN_STEM:
        return word
    for ending in ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM:
            return word[: -len(ending)]
    return word


def stems(text: str, drop_stop: bool = False) -> set[str]:
    """Множество основ всех слов фразы.

    Args:
        text: Исходная фраза.
        drop_stop: Выбросить служебные слова — нужно для запроса, но не
            для текста, где они могут оказаться частью смысла.
    """
    words = _WORD.findall(text)
    if drop_stop:
        # Отсеиваем до обрезки: «когда» после неё станет «когд»
        # и в списке служебных уже не найдётся.
        words = [w for w in words if w.lower().replace("ё", "е") not in STOP]
    return {stem(word) for word in words}


def score(query: str, text: str) -> int:
    """Сколько значимых слов запроса нашлось во фразе — в любой форме.

    Считаем, а не требуем всё сразу: люди спрашивают предложениями,
    и «что ты знаешь о моей работе» не обязано целиком лечь на факт.
    Ноль значит «не подходит», больше — тем вероятнее это то, что искали.
    """
    wanted = stems(query, drop_stop=True)
    if not wanted:
        return 1
    have = stems(text)
    return sum(1 for word in wanted if _found(word, have))


def matches(query: str, text: str) -> bool:
    """Нашлось ли во фразе хоть одно значимое слово запроса."""
    return score(query, text) > 0


def _found(word: str, have: set[str]) -> bool:
    """Ищет основу среди имеющихся, прощая расхождение в хвосте.

    Стеммер грубый и на близких словах может остановиться на разной длине.
    Поэтому длинные основы сравниваем по началу — но короткие только точно,
    иначе «код» найдётся в «кодексе».
    """
    if word in have:
        return True
    if len(word) < 4:
        return False
    return any(
        other.startswith(word) or word.startswith(other)
        for other in have
        if len(other) >= 4
    )


def _is_cyrillic(word: str) -> bool:
    return any("а" <= letter <= "я" for letter in word)
